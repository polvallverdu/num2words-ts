describe("Num2WordsCYTest", () => {
  test("test_number", () => {
    for (const test of TEST_CASES_CARDINAL) {
      expect(num2words(test[0], { lang: "cy" })).toBe(test[1]);
    }
  });

  test("test_number_fem", () => {
    for (const test of TEST_CASES_CARDINAL_FEM) {
      expect(num2words(test[0], { lang: "cy", gender: "fem" })).toBe(test[1]);
    }
  });

  test("test_number_not_implemented", () => {
    expect(() => num2words(10n ** 66n, { lang: "cy" })).toThrow(NotImplementedError);
  });

  test("test_decimals", () => {
    for (const test of TEST_CASES_DECIMALS) {
      expect(num2words(test[0], { lang: "cy" })).toBe(test[1]);
    }
  });

  test("test_ordinals", () => {
    for (const test of TEST_CASES_ORDINAL) {
      expect(num2words(test[0], { lang: "cy", to: "ordinal" })).toBe(test[1]);
    }
  });

  test("test_ordinal_not_implemented", () => {
    expect(() => num2words(101n, { lang: "cy", to: "ordinal" })).toThrow(NotImplementedError);
  });

  test("test_pounds", () => {
    for (const test of TEST_CASES_TO_CURRENCY_GBP) {
      expect(num2words(test[0], { lang: "cy", to: "currency", currency: "GBP" })).toBe(test[1]);
    }
  });

  test("test_other_cur", () => {
    expect(() => num2words(10.23, { lang: "cy", to: "currency", currency: "DEM" })).toThrow(
      NotImplementedError,
    );
  });

  test("test_counted", () => {
    for (const test of TEST_CASES_COUNTED) {
      expect(num2words(test[0], { lang: "cy", counted: test[1], gender: test[2] })).toBe(test[3]);
    }
  });
});

