  static lastFragmentToOrdinal(last: bigint, words: string[], level: number): void {
    const [n1, n2, n3] = getDigits(last) as [number, number, number];
    const lastTwo = n2 * 10 + n1;
    const hundredsOrd = (k: number) => (HUNDREDS_ORDINALS[k] as readonly string[])[level];
    if (lastTwo === 0) {
      words.push(hundredsOrd(n3) as string);
    } else if (level === 1 && last === 1n) {
      return;
    } else if (lastTwo < 20) {
      if (level === 0) {
        if (n3 > 0) {
          words.push((HUNDREDS[n3] as readonly string[])[0] as string);
        }
        words.push((ONES_ORDINALS[lastTwo] as readonly string[])[0] as string);
      } else {
        let lastFragmentString = "";
        if (n3 > 0) {
          lastFragmentString += (HUNDREDS_ORDINALS[n3] as readonly string[])[1];
        }
        lastFragmentString += (ONES_ORDINALS[lastTwo] as readonly string[])[1];
        words.push(lastFragmentString);
      }
    } else if (lastTwo % 10 === 0) {
      if (level === 0) {
        if (n3 > 0) {
          words.push((HUNDREDS[n3] as readonly string[])[0] as string);
        }
        words.push((TWENTIES_ORDINALS[n2] as readonly string[])[0] as string);
      } else {
        let lastFragmentString = "";
        if (n3 > 0) {
          lastFragmentString += (HUNDREDS_ORDINALS[n3] as readonly string[])[1];
        }
        lastFragmentString += (TWENTIES_ORDINALS[n2] as readonly string[])[1];
        words.push(lastFragmentString);
      }
    } else {
      if (level === 0) {
        if (n3 > 0) {
          words.push((HUNDREDS[n3] as readonly string[])[0] as string);
        }
        words.push((TWENTIES[n2] as readonly string[])[0] as string);
        words.push((ONES_ORDINALS[n1] as readonly string[])[0] as string);
      } else {
        let lastFragmentString = "";
        if (n3 > 0) {
          lastFragmentString += (HUNDREDS_ORDINALS[n3] as readonly string[])[1];
        }
        lastFragmentString += (TWENTIES_ORDINALS[n2] as readonly string[])[1];
        lastFragmentString += (ONES_ORDINALS[n1] as readonly string[])[1];
        words.push(lastFragmentString);
      }
    }
  }

  override toOrdinal(number: PyNum): string {
    this.verifyOrdinal(number);

    const words: string[] = [];
    const fragments = splitbyxStrictList(str(number), 3);
    let level = 0;
    let last = at(fragments, -1);
    while (last === 0n) {
      level = level + 1;
      fragments.pop();
      last = at(fragments, -1);
    }
    if (fragments.length > 1) {
      const sub = last * 1000n ** BigInt(level);
      const prePart = this._int2word(
        typeof number === "bigint" ? number - sub : toDecimalExact(number).sub(sub),
      );
      words.push(prePart);
    }
    Num2Word_UK.lastFragmentToOrdinal(last, words, level === 0 ? 0 : 1);
    let output = words.join(" ");
    if (last === 1n && level > 0 && output !== "") {
      output = `${output} `;
    }
    if (level > 0) {
      output = output + getItem(prefixes_ordinal, String(level));
    }
    return output;
  }
