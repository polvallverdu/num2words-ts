  override toCardinal(number: PyNum, options: CardinalOptions = {}): string {
    let morphologicalCase: number;
    if (Object.hasOwn(options, "case")) {
      const c = options.case;
      morphologicalCase = MORPHOLOGICAL_CASES.indexOf(c as string);
      if (morphologicalCase < 0) throw new ValueError(`${str(c)} is not in list`);
    } else {
      morphologicalCase = 0;
    }

    let gender: boolean;
    if (Object.hasOwn(options, "gender")) {
      gender = options.gender === "feminine";
    } else {
      gender = false;
    }

    const n = str(number).replaceAll(",", ".");
    if (n.includes(".")) {
      const parts = n.split(".");
      if (parts.length !== 2) {
        throw new ValueError(`too many values to unpack (expected 2, got ${parts.length})`);
      }
      const [left, right] = parts as [string, string];
      const leadingZeroCount = right.length - right.replace(/^0+/, "").length;
      const rightSide = this._int2word(int(right), gender, morphologicalCase);
      const decimalPart = `${ZERO[0]} `.repeat(leadingZeroCount) + rightSide;
      return `${this._int2word(int(left), gender, morphologicalCase)} ${this.pointword} ${decimalPart}`;
    }
    return this._int2word(int(n), gender, morphologicalCase);
  }

  override pluralize(n: bigint, forms: CurrencyForm): string {
    let form: number;
    if (mod(n, 100n) < 10n || mod(n, 100n) > 20n) {
      if (mod(n, 10n) === 1n) {
        form = 0;
      } else if (5n > mod(n, 10n) && mod(n, 10n) > 1n) {
        form = 1;
      } else {
        form = 2;
      }
    } else {
      form = 2;
    }

    return at(forms, form);
  }

  _int2word(n: PyNum, feminine = false, morphologicalCase = 0): string {
    if (cmp(n, 0n) < 0) {
      const nValue = this._int2word(abs(n), feminine, morphologicalCase);
      return [this.negword, nValue].join(" ");
    }

    if (eq(n, 0n)) {
      return ZERO[0];
    }

    const words: string[] = [];
    const chunks = splitbyxStrictList(str(n), 3);
    let i = chunks.length;
    for (const x of chunks) {
      i -= 1;

      if (x === 0n) {
        continue;
      }

      const [n1, n2, n3] = getDigits(x) as [number, number, number];

      if (n3 > 0) {
        words.push((HUNDREDS[n3] as readonly string[])[morphologicalCase] as string);
      }

      if (n2 > 1) {
        words.push((TWENTIES[n2] as readonly string[])[morphologicalCase] as string);
      }

      if (n2 === 1) {
        words.push((TENS[n1] as readonly string[])[morphologicalCase] as string);
        // elif n1 > 0 and not (i > 0 and x == 1):
      } else if (n1 > 0) {
        const ones = i === 1 || (feminine && i === 0) ? ONES_FEMININE : ONES;
        words.push((ones[n1] as readonly string[])[morphologicalCase] as string);
      }

      if (i > 0) {
        const thousandsVal = getItem(THOUSANDS, String(i))[morphologicalCase] as CurrencyForm;
        words.push(this.pluralize(x, thousandsVal));
      }
    }

    return words.join(" ");
  }

