"""Generate src/kwargs.ts: the keyword arguments each converter method accepts.

Python raises TypeError for an unexpected keyword argument; num2words() in the
port validates options against this table to do the same. Read from upstream's
method signatures with inspect.

Usage: python3 -I tools/gen_kwargs.py
"""

import inspect
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, ".upstream", "num2words"))
import num2words  # noqa: E402


def camel(name):
    return re.sub(r"_([a-z])", lambda m: m.group(1).upper(), name)


table = {}
for lang, conv in num2words.CONVERTER_CLASSES.items():
    methods = {}
    for to in num2words.CONVERTES_TYPES:
        method = getattr(conv, f"to_{to}", None)
        if method is None:
            continue  # upstream raises AttributeError; the port does too
        sig = inspect.signature(method)
        params = list(sig.parameters.values())[1:]  # first one is the number
        if any(p.kind == p.VAR_KEYWORD for p in params):
            methods[to] = None  # **kwargs: anything goes
        else:
            methods[to] = [camel(p.name) for p in params
                           if p.kind in (p.POSITIONAL_OR_KEYWORD, p.KEYWORD_ONLY)]
    table[lang] = methods

body = json.dumps(table, indent=2, ensure_ascii=False)
with open(os.path.join(ROOT, "src", "kwargs.ts"), "w", encoding="utf-8") as f:
    f.write(f"""// Copyright (c) 2026, num2words-ts contributors
// SPDX-License-Identifier: LGPL-2.1-or-later
//
// Generated by tools/gen_kwargs.py from upstream's method signatures; do not edit.
// The keyword arguments (camelCase) each converter's to_* method accepts, or
// null when it takes **kwargs. num2words() rejects anything else with a
// TypeError, like Python does.

export const ACCEPTED_KWARGS: Record<string, Record<string, readonly string[] | null>> = {body};
""")
print(f"{len(table)} languages")
